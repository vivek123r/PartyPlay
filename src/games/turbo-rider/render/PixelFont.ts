function parseGlyphRows(rows: string[]): [number, number][] {
  const pts: [number, number][] = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] === '#') pts.push([x, y]);
    }
  });
  return pts;
}

export const PIXEL_GLYPHS_LARGE: Record<string, [number, number][]> = Object.fromEntries(
  Object.entries(GLYPHS_5X7_ROWS).map(([ch, rows]) => [ch, parseGlyphRows(rows)])
);

export class PixelFont {
  public static drawText(
    g: Graphics,
    text: string,
    cx: number,
    cy: number,
    color: number,
    scale = 1,
    alpha = 1
  ): number {
    const s = scale;
    let x = cx;
    for (const ch of text.toUpperCase()) {
      const glyph = PIXEL_GLYPHS[ch];
      if (glyph) {
        for (const [gx, gy] of glyph) {
          g.rect(x + gx * s, cy + gy * s, s, s).fill({ color, alpha });
        }
        x += 3 * s;
      } else if (ch === ' ') {
        x += 3 * s;
      }
      x += s;
    }
    return x;
  }

  /** Larger, more legible 5x7 face — additive to `drawText`'s 3x5, same call shape and the same
   * "return the end X" contract. Advance is 6px/char at scale 1 (5 + 1 spacing). */
  public static drawTextLarge(
    g: Graphics,
    text: string,
    cx: number,
    cy: number,
    color: number,
    scale = 1,
    alpha = 1
  ): number {
    const s = scale;
    let x = cx;
    for (const ch of text.toUpperCase()) {
      const glyph = PIXEL_GLYPHS_LARGE[ch];
      if (glyph) {
        for (const [gx, gy] of glyph) {
          g.rect(x + gx * s, cy + gy * s, s, s).fill({ color, alpha });
        }
        x += 5 * s;
      } else if (ch === ' ') {
        x += 5 * s;
      }
      x += s;
    }
    return x;
  }

  /** Total advance `drawText` would produce for `text` at `scale` — matches the loop's own
   * `3*s` + `+= s` math exactly (`text.length * 4 * scale`), so callers can centre/right-align
   * text without duplicating that arithmetic (the old, error-prone `text.length * 4` literals
   * scattered across index.ts/BikeSprite.ts/GarageScreen.ts). */
  public static measure(text: string, scale = 1): number {
    return text.length * 4 * scale;
  }

  /** Same as `measure`, for `drawTextLarge` (5*s + s = 6px/char at scale 1). */
  public static measureLarge(text: string, scale = 1): number {
    return text.length * 6 * scale;
  }
}
